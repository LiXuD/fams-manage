import { mount, flushPromises } from "@vue/test-utils";
import { reactive } from "vue";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import RepairDraftView from "./RepairDraftView.vue";
const state=vi.hoisted(()=>({session:{user:{id:"1",roles:["ASSET_ADMIN"]},csrfToken:"csrf"},push:vi.fn()}));
vi.mock("@/auth/sessionStore",()=>({useSessionStore:()=>state.session}));
vi.mock("vue-router",()=>({useRouter:()=>({push:state.push})}));
const asset=()=>({id:"21",assetCode:"A-21",name:"打印机",version:6,lifecycle:"IN_USE",custodyType:"PERSONAL",locationId:"8",locationName:"原办公室"});
const response=(body:unknown,status=200)=>({ok:status===200,status,json:async()=>structuredClone(body)}) as Response;
const mountPage=()=>mount(RepairDraftView,{global:{stubs:{AppChrome:{template:`<main><slot name="actions" /><slot /></main>`},RouterLink:{props:["to"],template:`<a :data-destination="to"><slot /></a>`}}}});
const button=(wrapper:ReturnType<typeof mountPage>,text:string)=>wrapper.findAll("button").find(item=>item.text()===text)!;
async function fixture(fill = true) {
  const writes:RequestInit[]=[];
  vi.stubGlobal("fetch",vi.fn(async(_url:string,input:RequestInit)=>{if(input.method==="POST"){writes.push(input);return response({repairId:"77"});}return response({items:[asset()],total:1});}));
  const wrapper=mountPage();await flushPromises();
  await button(wrapper,"查找可报修资产").trigger("click");await flushPromises();
  await wrapper.find('input[type="radio"]').setValue(asset().id);
  await wrapper.find("textarea").setValue("实物无法正常启动");
  if (fill) await wrapper.find('input[type="datetime-local"]').setValue("2026-10-21T08:30");
  return {wrapper,writes};
}
beforeEach(()=>{state.session=reactive({user:{id:"1",roles:["ASSET_ADMIN"]},csrfToken:"csrf"});});
afterEach(()=>{vi.unstubAllGlobals();vi.restoreAllMocks();state.push.mockReset();});
describe("新建报修",()=>{
  it("建单页不发任何读请求，只给列表返回入口与管理员接续来源",async()=>{const request=vi.fn();vi.stubGlobal("fetch",request);const wrapper=mountPage();await flushPromises();
    expect(request).not.toHaveBeenCalled();
    expect(wrapper.text()).toContain("损坏归还接续维修");
    expect(wrapper.text()).toContain("提交报修");
    expect(wrapper.findAll("a[data-destination]").map(item=>[item.text(),item.attributes("data-destination")])).toEqual([["返回报修列表","/repairs"]]);
    wrapper.unmount();});
  it("非管理员不显示损坏归还接续维修入口",async()=>{state.session.user.roles=["EMPLOYEE"];vi.stubGlobal("fetch",vi.fn(async()=>response({items:[],total:0})));const wrapper=mountPage();await flushPromises();
    expect(wrapper.text()).not.toContain("损坏归还接续维修");expect(wrapper.text()).toContain("提交报修");wrapper.unmount();});
  it("缺资产、故障或发生时间时核对提交报修零写请求",async()=>{const f=await fixture(false);
    f.wrapper.findAll("button").find(item=>item.text()==="核对提交报修")!.trigger("click");await flushPromises();
    expect(f.writes).toHaveLength(0);expect(f.wrapper.text()).toContain("请选择资产并填写实际故障和发生时间。");
    expect(button(f.wrapper,"确认保存本次办理")).toBeUndefined();f.wrapper.unmount();});
  it("核对提交报修进入确认块，确认后按新单版本零提交实际故障并跳转详情",async()=>{const f=await fixture();
    button(f.wrapper,"核对提交报修").trigger("click");await flushPromises();
    expect(f.wrapper.find('[aria-label="确认本次报修办理"]').exists()).toBe(true);expect(f.writes).toHaveLength(0);
    button(f.wrapper,"确认保存本次办理").trigger("click");await flushPromises();
    expect(f.writes[0]).toMatchObject({method:"POST"});
    expect(JSON.parse(f.writes[0]!.body as string)).toEqual({assetId:"21",assetVersion:6,fault:"实物无法正常启动",impact:"MEDIUM",occurredAt:new Date("2026-10-21T08:30").toISOString()});
    expect((f.writes[0]!.headers as Record<string,string>)["If-Match-Version"]).toBe("0");
    expect(state.push).toHaveBeenCalledWith("/repairs/77?saved=1");f.wrapper.unmount();});
  it("响应丢失后重试沿用同一故障、影响程度、资产版本与幂等键",async()=>{const writes:RequestInit[]=[];let lost=true;
    vi.stubGlobal("fetch",vi.fn(async(_url:string,input:RequestInit)=>{if(input.method==="POST"){writes.push(input);if(lost){lost=false;throw new Error("lost response");}return response({repairId:"77"});}return response({items:[asset()],total:1});}));
    const wrapper=mountPage();await flushPromises();
    await button(wrapper,"查找可报修资产").trigger("click");await flushPromises();
    await wrapper.find('input[type="radio"]').setValue(asset().id);
    await wrapper.find("textarea").setValue("实物无法正常启动");
    await wrapper.find('input[type="datetime-local"]').setValue("2026-10-21T08:30");
    button(wrapper,"核对提交报修").trigger("click");await flushPromises();
    button(wrapper,"确认保存本次办理").trigger("click");await flushPromises();
    expect(writes).toHaveLength(1);expect(state.push).not.toHaveBeenCalled();
    button(wrapper,"重试原报修操作").trigger("click");await flushPromises();
    expect(writes).toHaveLength(2);expect(writes[1]).toEqual(writes[0]);
    expect(state.push).toHaveBeenCalledWith("/repairs/77?saved=1");wrapper.unmount();});
});
