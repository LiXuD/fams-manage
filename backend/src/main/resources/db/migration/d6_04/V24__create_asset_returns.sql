CREATE TABLE fams_asset_return (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    asset_id BIGINT NOT NULL,
    loan_id BIGINT NULL,
    asset_version BIGINT NOT NULL,
    responsible_employee_id BIGINT NOT NULL,
    using_organization_id BIGINT NOT NULL,
    proposed_by BIGINT NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    return_status VARCHAR(32) NOT NULL DEFAULT 'PENDING_APPROVAL',
    decided_by BIGINT NULL,
    decision_reason VARCHAR(1000) NULL,
    processor_account_id BIGINT NULL,
    inspection_result VARCHAR(20) NULL,
    inspection_reason VARCHAR(1000) NULL,
    warehouse_id BIGINT NULL,
    location_id BIGINT NULL,
    parameter_snapshot_json JSON NOT NULL,
    created_at DATETIME(3) NOT NULL,
    decided_at DATETIME(3) NULL,
    completed_at DATETIME(3) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    active_asset_id BIGINT GENERATED ALWAYS AS (CASE WHEN return_status IN
        ('PENDING_APPROVAL','WAITING_WAREHOUSE_CLAIM','WAREHOUSE_PROCESSING') THEN asset_id ELSE NULL END) STORED,
    UNIQUE KEY uk_return_active_asset (active_asset_id),
    KEY idx_return_pool (return_status,id),
    CONSTRAINT fk_return_asset FOREIGN KEY (asset_id) REFERENCES fams_asset(id),
    CONSTRAINT fk_return_loan FOREIGN KEY (loan_id) REFERENCES fams_loan(id),
    CONSTRAINT fk_return_responsible FOREIGN KEY (responsible_employee_id) REFERENCES fams_employee(id),
    CONSTRAINT fk_return_org FOREIGN KEY (using_organization_id) REFERENCES fams_organization(id),
    CONSTRAINT fk_return_proposer FOREIGN KEY (proposed_by) REFERENCES fams_system_account(id),
    CONSTRAINT fk_return_decider FOREIGN KEY (decided_by) REFERENCES fams_system_account(id),
    CONSTRAINT fk_return_processor FOREIGN KEY (processor_account_id) REFERENCES fams_system_account(id),
    CONSTRAINT fk_return_warehouse FOREIGN KEY (warehouse_id) REFERENCES fams_warehouse(id),
    CONSTRAINT fk_return_location FOREIGN KEY (location_id) REFERENCES fams_location(id),
    CONSTRAINT ck_return_status CHECK (return_status IN ('PENDING_APPROVAL','REJECTED',
        'WAITING_WAREHOUSE_CLAIM','WAREHOUSE_PROCESSING','COMPLETED','TRANSFERRED')),
    CONSTRAINT ck_return_inspection CHECK (inspection_result IS NULL OR inspection_result IN ('NORMAL','DAMAGED','MISSING')),
    CONSTRAINT ck_return_version CHECK (version >= 0 AND asset_version >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE fams_return_followup (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    return_id BIGINT NOT NULL,
    asset_id BIGINT NOT NULL,
    loan_id BIGINT NULL,
    business_type VARCHAR(20) NOT NULL,
    followup_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    processor_account_id BIGINT NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    created_at DATETIME(3) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    UNIQUE KEY uk_return_followup_source (return_id),
    CONSTRAINT fk_return_followup_source FOREIGN KEY (return_id) REFERENCES fams_asset_return(id),
    CONSTRAINT fk_return_followup_asset FOREIGN KEY (asset_id) REFERENCES fams_asset(id),
    CONSTRAINT fk_return_followup_loan FOREIGN KEY (loan_id) REFERENCES fams_loan(id),
    CONSTRAINT fk_return_followup_processor FOREIGN KEY (processor_account_id) REFERENCES fams_system_account(id),
    CONSTRAINT ck_return_followup_type CHECK (business_type IN ('REPAIR','LOST_REPORT')),
    CONSTRAINT ck_return_followup_status CHECK (followup_status IN ('PENDING','ACCEPTED','CLOSED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
