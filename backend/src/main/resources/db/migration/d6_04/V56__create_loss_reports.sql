-- Additive independent loss verification; no existing custody, loan or historical facts change.
CREATE TABLE fams_loss_report (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 asset_id BIGINT NOT NULL,
 creator_account_id BIGINT NOT NULL,
 using_organization_id BIGINT NULL,
 responsible_employee_id BIGINT NULL,
 shared_responsible_employee_id BIGINT NULL,
 asset_version BIGINT NOT NULL,
 source_snapshot_json LONGTEXT NOT NULL,
 last_seen_at DATETIME(3) NOT NULL,
 last_location VARCHAR(500) NOT NULL,
 circumstances VARCHAR(2000) NOT NULL,
 report_status VARCHAR(40) NOT NULL DEFAULT 'PENDING_ADMIN_DECISION',
 approval_snapshot_json LONGTEXT NULL,
 processor_account_id BIGINT NULL,
 ownership_version BIGINT NOT NULL DEFAULT 0,
 next_review_date DATE NULL,
 version BIGINT NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL,
 updated_at DATETIME(3) NOT NULL,
 CONSTRAINT fk_loss_asset FOREIGN KEY(asset_id) REFERENCES fams_asset(id),
 CONSTRAINT fk_loss_creator FOREIGN KEY(creator_account_id) REFERENCES fams_system_account(id),
 CONSTRAINT fk_loss_processor FOREIGN KEY(processor_account_id) REFERENCES fams_system_account(id),
 CONSTRAINT ck_loss_json CHECK(JSON_VALID(source_snapshot_json) AND (approval_snapshot_json IS NULL OR JSON_VALID(approval_snapshot_json))),
 CONSTRAINT ck_loss_status CHECK(report_status IN ('PENDING_ADMIN_DECISION','WAITING_WAREHOUSE_CLAIM','VERIFYING','SEARCHING','REJECTED','CANCELLED')),
 CONSTRAINT ck_loss_versions CHECK(version>=0 AND asset_version>=0 AND ownership_version>=0),
 INDEX ix_loss_pool(report_status,id),
 INDEX ix_loss_creator(creator_account_id,id),
 INDEX ix_loss_review(next_review_date,report_status,id)
);
CREATE TABLE fams_loss_event (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 report_id BIGINT NOT NULL,
 action VARCHAR(64) NOT NULL,
 before_version BIGINT NOT NULL,
 after_version BIGINT NOT NULL,
 actor_account_id BIGINT NOT NULL,
 actor_username VARCHAR(128) NOT NULL,
 actor_role VARCHAR(40) NOT NULL,
 detail_json LONGTEXT NOT NULL,
 occurred_at DATETIME(3) NOT NULL,
 CONSTRAINT fk_loss_event_report FOREIGN KEY(report_id) REFERENCES fams_loss_report(id),
 CONSTRAINT fk_loss_event_actor FOREIGN KEY(actor_account_id) REFERENCES fams_system_account(id),
 CONSTRAINT ck_loss_event_json CHECK(JSON_VALID(detail_json)),
 INDEX ix_loss_events(report_id,id)
);
CREATE TABLE fams_loss_receipt (
 actor_account_id BIGINT NOT NULL,
 operation VARCHAR(64) NOT NULL,
 request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 report_id BIGINT NOT NULL,
 payload_sha256 CHAR(64) NOT NULL,
 response_json LONGTEXT NOT NULL,
 created_at DATETIME(3) NOT NULL,
 PRIMARY KEY(actor_account_id,operation,request_id),
 CONSTRAINT fk_loss_receipt_report FOREIGN KEY(report_id) REFERENCES fams_loss_report(id),
 CONSTRAINT fk_loss_receipt_actor FOREIGN KEY(actor_account_id) REFERENCES fams_system_account(id),
 CONSTRAINT ck_loss_receipt_json CHECK(JSON_VALID(response_json))
);
