-- Additive repair-owned factory history; existing approvals and custody facts stay unchanged.
CREATE TABLE fams_repair_factory_scope (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 repair_id BIGINT NOT NULL,
 scope_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 allowed_method VARCHAR(40) NOT NULL DEFAULT 'FACTORY_NO_COST',
 request_snapshot_json LONGTEXT NOT NULL,
 request_reason VARCHAR(1000) NOT NULL,
 requested_by BIGINT NOT NULL,
 requested_at DATETIME(3) NOT NULL,
 decision_snapshot_json LONGTEXT NULL,
 decision_reason VARCHAR(1000) NULL,
 decided_by BIGINT NULL,
 decided_at DATETIME(3) NULL,
 version BIGINT NOT NULL DEFAULT 0,
 pending_repair_id BIGINT GENERATED ALWAYS AS (CASE WHEN scope_status='PENDING' THEN repair_id ELSE NULL END) STORED,
 UNIQUE KEY uk_factory_scope_pending(pending_repair_id),
 INDEX ix_factory_scope_repair(repair_id,id),
 CONSTRAINT fk_factory_scope_repair FOREIGN KEY(repair_id) REFERENCES fams_repair_request(id),
 CONSTRAINT fk_factory_scope_requester FOREIGN KEY(requested_by) REFERENCES fams_system_account(id),
 CONSTRAINT fk_factory_scope_decider FOREIGN KEY(decided_by) REFERENCES fams_system_account(id),
 CONSTRAINT ck_factory_scope_status CHECK(scope_status IN ('PENDING','APPROVED','REJECTED','WITHDRAWN')),
 CONSTRAINT ck_factory_scope_method CHECK(allowed_method='FACTORY_NO_COST'),
 CONSTRAINT ck_factory_scope_version CHECK(version>=0),
 CONSTRAINT ck_factory_scope_json CHECK(JSON_VALID(request_snapshot_json) AND (decision_snapshot_json IS NULL OR JSON_VALID(decision_snapshot_json))),
 CONSTRAINT ck_factory_scope_decision CHECK((scope_status='PENDING' AND decided_by IS NULL AND decided_at IS NULL AND decision_reason IS NULL AND decision_snapshot_json IS NULL) OR (scope_status<>'PENDING' AND decided_by IS NOT NULL AND decided_at IS NOT NULL AND decision_reason IS NOT NULL AND decision_snapshot_json IS NOT NULL))
);
CREATE TABLE fams_repair_factory_round (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 repair_id BIGINT NOT NULL,
 asset_id BIGINT NOT NULL,
 scope_id BIGINT NOT NULL,
 round_number INT NOT NULL,
 round_status VARCHAR(24) NOT NULL DEFAULT 'PENDING_DISPATCH',
 provider_name VARCHAR(200) NOT NULL,
 service_contact VARCHAR(100) NOT NULL,
 service_phone VARCHAR(64) NOT NULL,
 expected_return_date DATE NOT NULL,
 fault VARCHAR(2000) NOT NULL,
 original_identity_json LONGTEXT NOT NULL,
 created_by BIGINT NOT NULL,
 created_at DATETIME(3) NOT NULL,
 dispatched_at DATETIME(3) NULL,
 dispatched_by BIGINT NULL,
 dispatch_evidence VARCHAR(2000) NULL,
 received_at DATETIME(3) NULL,
 received_by BIGINT NULL,
 receive_location_id BIGINT NULL,
 receive_location_version BIGINT NULL,
 condition_result VARCHAR(24) NULL,
 treatment_result VARCHAR(2000) NULL,
 actual_cost DECIMAL(14,2) NULL,
 cancel_reason VARCHAR(1000) NULL,
 version BIGINT NOT NULL DEFAULT 0,
 active_asset_id BIGINT GENERATED ALWAYS AS (CASE WHEN round_status IN ('PENDING_DISPATCH','DISPATCHED') THEN asset_id ELSE NULL END) STORED,
 UNIQUE KEY uk_factory_round_number(repair_id,round_number),
 UNIQUE KEY uk_factory_round_active_asset(active_asset_id),
 INDEX ix_factory_round_repair(repair_id,id),
 CONSTRAINT fk_factory_round_repair FOREIGN KEY(repair_id) REFERENCES fams_repair_request(id),
 CONSTRAINT fk_factory_round_asset FOREIGN KEY(asset_id) REFERENCES fams_asset(id),
 CONSTRAINT fk_factory_round_scope FOREIGN KEY(scope_id) REFERENCES fams_repair_factory_scope(id),
 CONSTRAINT fk_factory_round_creator FOREIGN KEY(created_by) REFERENCES fams_system_account(id),
 CONSTRAINT fk_factory_round_dispatcher FOREIGN KEY(dispatched_by) REFERENCES fams_system_account(id),
 CONSTRAINT fk_factory_round_receiver FOREIGN KEY(received_by) REFERENCES fams_system_account(id),
 CONSTRAINT fk_factory_round_location FOREIGN KEY(receive_location_id) REFERENCES fams_location(id),
 CONSTRAINT ck_factory_round_status CHECK(round_status IN ('PENDING_DISPATCH','DISPATCHED','RECEIVED','CANCELLED')),
 CONSTRAINT ck_factory_round_numbers CHECK(round_number>0 AND version>=0 AND (receive_location_version IS NULL OR receive_location_version>=0)),
 CONSTRAINT ck_factory_round_identity CHECK(JSON_VALID(original_identity_json)),
 CONSTRAINT ck_factory_round_dispatch CHECK((round_status IN ('PENDING_DISPATCH','CANCELLED') AND dispatched_at IS NULL AND dispatched_by IS NULL AND dispatch_evidence IS NULL) OR (round_status IN ('DISPATCHED','RECEIVED') AND dispatched_at IS NOT NULL AND dispatched_by IS NOT NULL AND dispatch_evidence IS NOT NULL AND dispatched_at>=created_at)),
 CONSTRAINT ck_factory_round_receipt CHECK((round_status<>'RECEIVED' AND received_at IS NULL AND received_by IS NULL AND receive_location_id IS NULL AND receive_location_version IS NULL AND condition_result IS NULL AND treatment_result IS NULL AND actual_cost IS NULL) OR (round_status='RECEIVED' AND received_at IS NOT NULL AND received_at>=dispatched_at AND received_by IS NOT NULL AND receive_location_id IS NOT NULL AND receive_location_version IS NOT NULL AND condition_result IS NOT NULL AND condition_result IN ('RESTORED','STILL_FAULTY') AND treatment_result IS NOT NULL AND actual_cost IS NOT NULL AND actual_cost=0)),
 CONSTRAINT ck_factory_round_cancel CHECK((round_status='CANCELLED' AND cancel_reason IS NOT NULL) OR (round_status<>'CANCELLED' AND cancel_reason IS NULL))
);
CREATE TABLE fams_repair_factory_event (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 repair_id BIGINT NOT NULL,
 scope_id BIGINT NULL,
 round_id BIGINT NULL,
 action VARCHAR(64) NOT NULL,
 before_version BIGINT NOT NULL,
 after_version BIGINT NOT NULL,
 actor_account_id BIGINT NOT NULL,
 actor_username VARCHAR(128) NOT NULL,
 actor_role VARCHAR(40) NOT NULL,
 detail_json LONGTEXT NOT NULL,
 recorded_at DATETIME(3) NOT NULL,
 INDEX ix_factory_event_repair(repair_id,id),
 CONSTRAINT fk_factory_event_repair FOREIGN KEY(repair_id) REFERENCES fams_repair_request(id),
 CONSTRAINT fk_factory_event_scope FOREIGN KEY(scope_id) REFERENCES fams_repair_factory_scope(id),
 CONSTRAINT fk_factory_event_round FOREIGN KEY(round_id) REFERENCES fams_repair_factory_round(id),
 CONSTRAINT fk_factory_event_actor FOREIGN KEY(actor_account_id) REFERENCES fams_system_account(id),
 CONSTRAINT ck_factory_event_versions CHECK(before_version>=0 AND after_version>=before_version),
 CONSTRAINT ck_factory_event_json CHECK(JSON_VALID(detail_json))
);
CREATE TABLE fams_repair_factory_evidence (
 object_id CHAR(36) NOT NULL PRIMARY KEY,
 repair_id BIGINT NOT NULL,
 round_id BIGINT NOT NULL,
 purpose VARCHAR(24) NOT NULL,
 content_sha256 CHAR(64) NOT NULL,
 uploader_account_id BIGINT NOT NULL,
 recorded_at DATETIME(3) NOT NULL,
 INDEX ix_factory_evidence_round(round_id,purpose,object_id),
 CONSTRAINT fk_factory_evidence_object FOREIGN KEY(object_id) REFERENCES fams_attachment(object_id),
 CONSTRAINT fk_factory_evidence_repair FOREIGN KEY(repair_id) REFERENCES fams_repair_request(id),
 CONSTRAINT fk_factory_evidence_round FOREIGN KEY(round_id) REFERENCES fams_repair_factory_round(id),
 CONSTRAINT fk_factory_evidence_uploader FOREIGN KEY(uploader_account_id) REFERENCES fams_system_account(id),
 CONSTRAINT ck_factory_evidence_purpose CHECK(purpose IN ('FAULT','FACTORY_ACK','RECEIPT'))
);
