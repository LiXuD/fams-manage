CREATE TABLE fams_inbound_receipt (
    id BIGINT NOT NULL AUTO_INCREMENT,
    receipt_no VARCHAR(128) NOT NULL,
    creator_account_id BIGINT NOT NULL,
    creator_username_snapshot VARCHAR(128) NOT NULL,
    receipt_status VARCHAR(40) NOT NULL,
    business_date DATE NOT NULL,
    parameter_version_id BIGINT NOT NULL,
    timezone_snapshot VARCHAR(64) NOT NULL,
    admin_decision_deadline_workdays TINYINT UNSIGNED NOT NULL,
    warehouse_claim_deadline_workdays TINYINT UNSIGNED NOT NULL,
    warehouse_first_execution_deadline_workdays TINYINT UNSIGNED NOT NULL,
    submitted_at DATETIME(3) NULL,
    admin_decision_due_at DATETIME(3) NULL,
    warehouse_claim_due_at DATETIME(3) NULL,
    warehouse_first_execution_due_at DATETIME(3) NULL,
    notes VARCHAR(2000) NULL,
    cancelled_at DATETIME(3) NULL,
    cancellation_reason VARCHAR(500) NULL,
    completed_at DATETIME(3) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    created_by BIGINT NOT NULL,
    updated_by BIGINT NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_inbound_receipt_no (receipt_no),
    KEY idx_inbound_status (receipt_status, id),
    CONSTRAINT fk_inbound_creator FOREIGN KEY (creator_account_id) REFERENCES fams_system_account(id),
    CONSTRAINT fk_inbound_parameter FOREIGN KEY (parameter_version_id) REFERENCES fams_business_parameter_version(id),
    CONSTRAINT ck_inbound_status CHECK (receipt_status IN (
        'DRAFT', 'PENDING_ADMIN_DECISION', 'REJECTED', 'WAITING_WAREHOUSE_CLAIM',
        'WAREHOUSE_PROCESSING', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_inbound_deadlines CHECK (
        admin_decision_deadline_workdays BETWEEN 1 AND 30
        AND warehouse_claim_deadline_workdays BETWEEN 1 AND 30
        AND warehouse_first_execution_deadline_workdays BETWEEN 1 AND 30),
    CONSTRAINT ck_inbound_version CHECK (version >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE fams_inbound_receipt_item (
    id BIGINT NOT NULL AUTO_INCREMENT,
    receipt_id BIGINT NOT NULL,
    asset_id BIGINT NOT NULL,
    asset_version_snapshot BIGINT NOT NULL,
    asset_code_snapshot VARCHAR(128) NOT NULL,
    asset_name_snapshot VARCHAR(256) NOT NULL,
    target_warehouse_id BIGINT NOT NULL,
    warehouse_version_snapshot BIGINT NOT NULL,
    warehouse_code_snapshot VARCHAR(64) NOT NULL,
    warehouse_name_snapshot VARCHAR(128) NOT NULL,
    target_location_id BIGINT NOT NULL,
    location_version_snapshot BIGINT NOT NULL,
    location_code_snapshot VARCHAR(64) NOT NULL,
    location_name_snapshot VARCHAR(128) NOT NULL,
    execution_status VARCHAR(20) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_inbound_receipt_asset (receipt_id, asset_id),
    KEY idx_inbound_target_warehouse (target_warehouse_id, receipt_id),
    KEY idx_inbound_target_location (target_location_id, receipt_id),
    CONSTRAINT fk_inbound_item_receipt FOREIGN KEY (receipt_id) REFERENCES fams_inbound_receipt(id) ON DELETE RESTRICT,
    CONSTRAINT fk_inbound_item_asset FOREIGN KEY (asset_id) REFERENCES fams_asset(id),
    CONSTRAINT fk_inbound_item_warehouse FOREIGN KEY (target_warehouse_id) REFERENCES fams_warehouse(id),
    CONSTRAINT fk_inbound_item_location FOREIGN KEY (target_location_id) REFERENCES fams_location(id),
    CONSTRAINT ck_inbound_item_status CHECK (execution_status IN ('PENDING', 'ACCEPTED')),
    CONSTRAINT ck_inbound_item_version CHECK (version >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
