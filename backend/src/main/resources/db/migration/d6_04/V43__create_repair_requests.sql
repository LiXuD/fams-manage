-- Repair owns approvals and processing; asset and loan facts remain owned by their public ports.
CREATE TABLE fams_repair_request (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 asset_id BIGINT NOT NULL,
 creator_account_id BIGINT NOT NULL,
 using_organization_id BIGINT NULL,
 responsible_employee_id BIGINT NULL,
 shared_responsible_employee_id BIGINT NULL,
 asset_version BIGINT NOT NULL,
 source_snapshot_json LONGTEXT NOT NULL,
 loan_snapshot_json LONGTEXT NULL,
 timezone_id VARCHAR(64) NOT NULL,
 fault VARCHAR(2000) NOT NULL,
 impact VARCHAR(16) NOT NULL,
 occurred_at DATETIME(3) NOT NULL,
 repair_status VARCHAR(40) NOT NULL DEFAULT 'PENDING_ADMIN_DECISION',
 allowed_method VARCHAR(40) NULL,
 approval_snapshot_json LONGTEXT NULL,
 processor_account_id BIGINT NULL,
 ownership_version BIGINT NOT NULL DEFAULT 0,
 claimed_at DATETIME(3) NULL,
 accepted_at DATETIME(3) NULL,
 completed_at DATETIME(3) NULL,
 version BIGINT NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL,
 updated_at DATETIME(3) NOT NULL,
 CONSTRAINT fk_repair_asset FOREIGN KEY(asset_id) REFERENCES fams_asset(id),
 CONSTRAINT fk_repair_creator FOREIGN KEY(creator_account_id) REFERENCES fams_system_account(id),
 CONSTRAINT fk_repair_processor FOREIGN KEY(processor_account_id) REFERENCES fams_system_account(id),
 CONSTRAINT ck_repair_json CHECK(JSON_VALID(source_snapshot_json) AND (loan_snapshot_json IS NULL OR JSON_VALID(loan_snapshot_json)) AND (approval_snapshot_json IS NULL OR JSON_VALID(approval_snapshot_json))),
 CONSTRAINT ck_repair_impact CHECK(impact IN ('LOW','MEDIUM','HIGH')),
 CONSTRAINT ck_repair_status CHECK(repair_status IN ('PENDING_ADMIN_DECISION','WAITING_WAREHOUSE_CLAIM','WAREHOUSE_PROCESSING','COMPLETED','REJECTED','CANCELLED')),
 CONSTRAINT ck_repair_versions CHECK(version>=0 AND asset_version>=0 AND ownership_version>=0),
 INDEX ix_repair_pool(repair_status,id),
 INDEX ix_repair_creator(creator_account_id,id)
);
CREATE TABLE fams_repair_decision (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 repair_id BIGINT NOT NULL,
 before_version BIGINT NOT NULL,
 after_version BIGINT NOT NULL,
 result VARCHAR(16) NOT NULL,
 allowed_method VARCHAR(40) NULL,
 snapshot_json LONGTEXT NOT NULL,
 reason VARCHAR(1000) NOT NULL,
 actor_account_id BIGINT NOT NULL,
 recorded_at DATETIME(3) NOT NULL,
 UNIQUE KEY uk_repair_decision_version(repair_id,before_version),
 CONSTRAINT fk_repair_decision_request FOREIGN KEY(repair_id) REFERENCES fams_repair_request(id),
 CONSTRAINT fk_repair_decision_actor FOREIGN KEY(actor_account_id) REFERENCES fams_system_account(id),
 CONSTRAINT ck_repair_decision_result CHECK(result IN ('APPROVE','REJECT')),
 CONSTRAINT ck_repair_decision_version CHECK(before_version>=0 AND after_version=before_version+1),
 CONSTRAINT ck_repair_decision_json CHECK(JSON_VALID(snapshot_json))
);
CREATE TABLE fams_repair_event (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 repair_id BIGINT NOT NULL,
 action VARCHAR(64) NOT NULL,
 before_version BIGINT NOT NULL,
 after_version BIGINT NOT NULL,
 actor_account_id BIGINT NOT NULL,
 actor_username VARCHAR(128) NOT NULL,
 actor_role VARCHAR(40) NOT NULL,
 detail_json LONGTEXT NOT NULL,
 occurred_at DATETIME(3) NOT NULL,
 CONSTRAINT fk_repair_event_request FOREIGN KEY(repair_id) REFERENCES fams_repair_request(id),
 CONSTRAINT fk_repair_event_actor FOREIGN KEY(actor_account_id) REFERENCES fams_system_account(id),
 CONSTRAINT ck_repair_event_json CHECK(JSON_VALID(detail_json))
);
CREATE TABLE fams_repair_receipt (
 actor_account_id BIGINT NOT NULL,
 operation VARCHAR(64) NOT NULL,
 request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 repair_id BIGINT NOT NULL,
 payload_sha256 CHAR(64) NOT NULL,
 response_json LONGTEXT NOT NULL,
 created_at DATETIME(3) NOT NULL,
 PRIMARY KEY(actor_account_id,operation,request_id),
 CONSTRAINT fk_repair_receipt_request FOREIGN KEY(repair_id) REFERENCES fams_repair_request(id),
 CONSTRAINT fk_repair_receipt_actor FOREIGN KEY(actor_account_id) REFERENCES fams_system_account(id),
 CONSTRAINT ck_repair_receipt_json CHECK(JSON_VALID(response_json))
);
CREATE TABLE fams_repair_photo (
 object_id CHAR(36) PRIMARY KEY,
 repair_id BIGINT NOT NULL,
 purpose VARCHAR(24) NOT NULL,
 content_sha256 CHAR(64) NOT NULL,
 uploader_account_id BIGINT NOT NULL,
 recorded_at DATETIME(3) NOT NULL,
 CONSTRAINT fk_repair_photo_object FOREIGN KEY(object_id) REFERENCES fams_attachment(object_id),
 CONSTRAINT fk_repair_photo_request FOREIGN KEY(repair_id) REFERENCES fams_repair_request(id),
 CONSTRAINT fk_repair_photo_actor FOREIGN KEY(uploader_account_id) REFERENCES fams_system_account(id),
 INDEX ix_repair_photo(repair_id,purpose,object_id)
);
